/**
 * One-shot: pulls Vietnam administrative data from provinces.open-api.vn API v2
 * (34 provincial units + wards via ?depth=2), keeps only fields we need, then writes:
 * - backend/src/data/vn/provinces.json
 * - backend/src/data/vn/wards.json
 * - frontend/src/constants/vnAdministrative.ts
 *
 * Run from repo root: node backend/scripts/fetch-vn-openapi-to-static.mjs
 * Requires Node 18+ (fetch).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const backendRoot = path.join(__dirname, "..");
const feConstants = path.join(backendRoot, "..", "frontend", "src", "constants");

const BASE = "https://provinces.open-api.vn/api/v2";

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) {
    const t = await res.text();
    throw new Error(`${url} → ${res.status}: ${t.slice(0, 200)}`);
  }
  return res.json();
}

async function main() {
  console.log("GET", `${BASE}/`);
  const list = await getJson(`${BASE}/`);
  if (!Array.isArray(list)) throw new Error("Expected array from /api/v2/");

  const provinces = list.map((p) => ({
    provinceCode: String(p.code),
    provinceName: p.name,
  }));

  const wards = [];
  for (const p of list) {
    const url = `${BASE}/p/${p.code}?depth=2`;
    process.stdout.write(`GET ${url} … `);
    const detail = await getJson(url);
    const wlist = detail.wards || [];
    for (const w of wlist) {
      wards.push({
        provinceCode: String(p.code),
        wardCode: String(w.code),
        wardName: w.name,
      });
    }
    console.log(wlist.length, "wards");
  }

  const vnDir = path.join(backendRoot, "src", "data", "vn");
  fs.mkdirSync(vnDir, { recursive: true });
  fs.writeFileSync(path.join(vnDir, "provinces.json"), JSON.stringify(provinces, null, 2), "utf8");
  fs.writeFileSync(path.join(vnDir, "wards.json"), JSON.stringify(wards), "utf8");

  fs.mkdirSync(feConstants, { recursive: true });
  const ts = `/** Auto-generated by backend/scripts/fetch-vn-openapi-to-static.mjs — source: https://provinces.open-api.vn/api/v2/ Re-run to refresh. */

export type VnProvinceItem = { provinceCode: string; provinceName: string };
export type VnWardItem = { provinceCode: string; wardCode: string; wardName: string };

export const VN_PROVINCES: VnProvinceItem[] = ${JSON.stringify(provinces, null, 2)};

export const VN_WARDS: VnWardItem[] = ${JSON.stringify(wards, null, 2)};

export function vnWardsForProvince(provinceCode: string): VnWardItem[] {
  return VN_WARDS.filter((w) => w.provinceCode === provinceCode);
}
`;
  fs.writeFileSync(path.join(feConstants, "vnAdministrative.ts"), ts, "utf8");

  console.log("Wrote", provinces.length, "provinces,", wards.length, "wards");
  console.log("→ backend/src/data/vn/{provinces,wards}.json");
  console.log("→ frontend/src/constants/vnAdministrative.ts");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
